import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const rows = [];
// This release uses the old plural "licenses" key, absent from npm's lock data.
// Its published LICENSE offers MIT or GPL-2.0; the optional probe selects MIT.
const reviewedLicences = {
  'jquery-touchswipe@1.6.19': 'MIT (dual-licence option)',
};
for (const component of ['.', 'service', 'scripts/runtime']) {
  const lock = JSON.parse(
    readFileSync(resolve(root, component, 'package-lock.json'), 'utf8'),
  );
  for (const [path, pkg] of Object.entries(lock.packages)) {
    if (!path) continue;
    const name = pkg.name ?? path.split('node_modules/').at(-1);
    rows.push([
      component === '.'
        ? 'tooling'
        : component === 'service'
          ? 'service'
          : 'runtime-probe',
      name,
      pkg.version,
      pkg.license ??
        reviewedLicences[`${name}@${pkg.version}`] ??
        'REVIEW REQUIRED',
    ]);
  }
}
rows.sort((a, b) => a.join('/').localeCompare(b.join('/')));
const document = [
  '# Locked npm dependency licences',
  '',
  'Generated by `node scripts/dependency-licences.mjs` from all three committed lockfiles.',
  'Includes runtime, development and optional platform packages. Preserve upstream notices.',
  '',
  '| Component | Package | Version | Licence |',
  '| --- | --- | --- | --- |',
  ...rows.map((row) => `| ${row.join(' | ')} |`),
  '',
].join('\n');
writeFileSync(resolve(root, 'docs/dependency-licences.md'), document);
console.log(`Recorded ${rows.length} locked dependency entries.`);
